# Set some variables
wall_dir="${HOME}/dots/Wallpapers/"
cacheDir="${HOME}/.cache/jp/${theme}"
rofi_command="rofi -dmenu -theme ${HOME}/dots/rofi/wallSelect.rasi -theme-str ${rofi_override}"

# Create cache dir if not exists
if [ ! -d "${cacheDir}" ] ; then
        mkdir -p "${cacheDir}"
    fi


physical_monitor_size=12
monitor_res=$(hyprctl monitors |grep -A2 Monitor |head -n 2 |awk '{print $1}' | grep -oE '^[0-9]+')
dotsperinch=$(echo "scale=2; $monitor_res / $physical_monitor_size" | bc | xargs printf "%.0f")
monitor_res=$(( $monitor_res * $physical_monitor_size / $dotsperinch ))

rofi_override="element-icon{size:${monitor_res}px;border-radius:1px;}"

# Convert images in directory and save to cache dir
for imagen in "$wall_dir"/*.{jpg,jpeg,png,webp}; do
	if [ -f "$imagen" ]; then
		nombre_archivo=$(basename "$imagen")
			if [ ! -f "${cacheDir}/${nombre_archivo}" ] ; then
				magick convert -strip "$imagen" -thumbnail 1280x720^ -gravity center -extent 1280x720 "${cacheDir}/${nombre_archivo}"
			fi
    fi
done

# Select a picture with rofi
# wall_selection=$(find "${wall_dir}"  -maxdepth 1  -type f \( -iname "*.jpg" -o -iname "*.jpeg" -o -iname "*.png" -o -iname "*.webp" \) -exec basename {} \; | sort | while read -r A ; do  echo -en "$A\x00icon\x1f""${cacheDir}"/"$A\n" ; done | $rofi_command)

# Select a picture with rofi
wall_selection=$(
    find "${wall_dir}" -maxdepth 1 -type f \
        \( -iname "*.jpg" -o -iname "*.jpeg" -o -iname "*.png" -o -iname "*.webp" \) |
    sort |
    while read -r A; do

        # Original filename
        filename=$(basename "$A")

        # Display name:
        # remove extension
        # replace _ and - with spaces
        # capitalize each word
        display_name=$(basename "$filename" | sed -E 's/\.(jpg|jpeg|png|webp)$//I' |
            sed -E 's/[_-]+/ /g' |
            sed -E 's/(^| )([a-z])/\1\u\2/g')

        # Send original filename as the selected value,
        # but display the formatted name in Rofi
        printf '%s\x00icon\x1f%s\x1fdisplay\x1f%s\n' \
            "$filename" \
            "${cacheDir}/${filename}" \
            "$display_name"

    done |
    rofi -dmenu \
        -theme "${HOME}/dots/rofi/wallSelect.rasi" \
        -theme-str "${rofi_override}"
)

# Set the wallpaper
[[ -n "$wall_selection" ]] || exit 1
awww img ${wall_dir}/${wall_selection} -t fade --transition-duration 1.5

exit 0

